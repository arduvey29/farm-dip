/*
  Builds the generated parts of the Shopify theme in /shopify:
    assets/farm-dip.css  Tailwind, compiled from src/app/globals.css (the same tokens, components and
                         living-art CSS as the Next site) against the classes used in the Liquid files
    assets/farm-dip.js   src/lib/motion.ts (the site's framework-free motion) + shopify/src/theme.js
    assets/*             fonts, brand art, farm photos, the QR code and the hero video, copied from the site

  Run: npm run theme:build   (then `npm run theme:dev` or `npm run theme:push`)

  The Fontshare fonts (Author, General Sans) are copied from src/assets/fonts/fontshare, which
  scripts/fetch-fonts.mjs downloads. Their licence allows self-hosting on our own store but not
  redistribution, so the copies in shopify/assets are git-ignored and only ever uploaded to Shopify.
*/
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, optimize } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";
import ts from "typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const theme = join(root, "shopify");
const assets = join(theme, "assets");
mkdirSync(assets, { recursive: true });

/* ---------- Static files ---------- */
const copies = [
  ["src/assets/fonts/fontshare/Author-Variable.woff2", "Author-Variable.woff2"],
  ["src/assets/fonts/fontshare/Author-VariableItalic.woff2", "Author-VariableItalic.woff2"],
  ["src/assets/fonts/fontshare/GeneralSans-Variable.woff2", "GeneralSans-Variable.woff2"],
  ["src/assets/fonts/adobe-caslon/ACaslonPro-Regular.woff2", "ACaslonPro-Regular.woff2"],
  ["src/assets/fonts/adobe-caslon/ACaslonPro-Semibold.woff2", "ACaslonPro-Semibold.woff2"],
  ["src/assets/fonts/adobe-caslon/ACaslonPro-Bold.woff2", "ACaslonPro-Bold.woff2"],
  ["src/assets/fonts/Eczar-Bold.ttf", "Eczar-Bold.ttf"],
  ["public/images/brand/farm-dip-badge.svg", "farm-dip-badge.svg"],
  ["public/images/brand/farm-dip-emblem.svg", "farm-dip-emblem.svg"],
  ["public/images/report/test-report-qr.png", "test-report-qr.png"],
  ["public/video/farmdip vid.mp4", "farm-dip-video.mp4"],
  ...["a1", "a2", "a3", "a4", "c1", "c2", "c3", "c4", "c5", "c6"].map((n) => [`public/images/farm/${n}.jpeg`, `farm-${n}.jpeg`]),
  ...["jar", "jar-1l", "dolchi", "sizes", "texture"].map((n) => [`public/images/products/pure-desi-buffalo-ghee/${n}.svg`, `ghee-${n}.svg`]),
];
let missing = 0;
for (const [from, to] of copies) {
  const src = join(root, from);
  if (!existsSync(src)) {
    console.warn(`missing ${from}${from.includes("fontshare") ? " (run npm run fonts)" : ""}`);
    missing++;
    continue;
  }
  copyFileSync(src, join(assets, to));
}

/* ---------- CSS ---------- */
// The site's stylesheet, minus its Tailwind import, plus the theme's own @font-face rules.
const siteCss = readFileSync(join(root, "src/app/globals.css"), "utf8").replace('@import "tailwindcss";', "");
const themeCss = readFileSync(join(theme, "src/theme.css"), "utf8");
const input = `@import "tailwindcss" source(none);
@source "../layout";
@source "../sections";
@source "../snippets";
@source "../templates";
@source "./theme.js";
${themeCss}
${siteCss}`;
const base = join(theme, "src");
const compiler = await compile(input, { base, onDependency: () => {} });
const scanner = new Scanner({ sources: compiler.sources });
const built = compiler.build(scanner.scan());
const { code: css } = optimize(built, { minify: true });
writeFileSync(join(assets, "farm-dip.css"), css);

/* ---------- JS ---------- */
const motion = ts.transpileModule(readFileSync(join(root, "src/lib/motion.ts"), "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false },
}).outputText;
const themeJs = readFileSync(join(theme, "src/theme.js"), "utf8");
writeFileSync(join(assets, "farm-dip.js"), `/* Generated by scripts/build-theme.mjs. Edit src/lib/motion.ts or shopify/src/theme.js. */\n${motion}\n${themeJs}`);

console.log(`theme built: farm-dip.css ${(css.length / 1024).toFixed(0)} KB, ${copies.length - missing}/${copies.length} files copied`);
if (missing) process.exitCode = 1;
